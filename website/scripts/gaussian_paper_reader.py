def lean_fold(label, text, code, url):
    return (f'<details class="companion-lean gp-code"><summary>{label}</summary>'
            f'<p>{text}</p><pre><code class="language-lean">{escape(code)}</code></pre>'
            f'<p>{link(url, "Read the full module at the reviewed revision")}</p></details>')


def theorem(t, record, blob, prose):
    key = t["id"]
    number, heading, idea, conditions, why, bridge, anchor = GUIDES[key]
    item = record["theorems"][key]
    source = blob + record["root"] + "/" + item["file"] + "#L" + str(item["line"])
    signature, proof = item["excerpt"].split(" := by\n", 1)
    steps = []
    for i, (step, path) in enumerate(zip(t["steps"], item["step_sources"], strict=True), 1):
        steps.append(f'<li id="{key}-step-{i:02d}"><h4>{escape(step["title"])}</h4>'
                     + formula_html(step["formula"]) + f'<p>{prose(step["text"])}</p>'
                     + '<details class="gp-source"><summary>Sources for this step</summary><p>'
                     + link(PAPER + anchor, step["anchor"]) + ' · '
                     + link(blob + path, "Related Lean module") + '</p></details></li>')
    return (f'<section class="gp-result" id="{key}"><p class="gp-kicker">Theorem {number}</p>'
            f'<h3>{heading}</h3><p>{idea}</p><p>{conditions}</p>' + formula_html(t["formula"])
            + lean_fold("Read the Lean statement", "Exact signature in the public replay.", signature, source)
            + f'<details class="companion-proof-route gp-route" id="{key}-proof">'
            + f'<summary>Why the bound holds · Theorem {number}</summary><p>{why}</p>'
            + '<details class="gp-calculation"><summary>Follow the calculation step by step</summary><ol>'
            + ''.join(steps) + '</ol></details>'
            + lean_fold("Read the Lean proof", bridge, "by\n" + proof, source)
            + f'<p>{link(PAPER + anchor, "Read Theorem " + number + " in the paper")}</p></details></section>')


def contours():
    # Both drawings have identical semiaxes. Only the ellipse orientation changes.
    plots = []
    for cx, angle in ((42, -28), (137, 35)):
        ellipses = ''.join(f'<ellipse rx="{a}" ry="{b}"/>' for a, b in ((12, 5), (23, 10), (35, 15)))
        plots.append(f'<g transform="translate({cx} 37)"><path d="M-37 0h74 M0 -33v66" opacity=".24"/>'
                     f'<g transform="rotate({angle})">{ellipses}</g></g>')
    return ('<figure class="gp-figure"><svg viewBox="0 0 180 75" role="img" aria-label="Two Gaussian density contours with the same axis lengths but different orientations" '
            'fill="none" stroke="currentColor" stroke-width="1.7">' + ''.join(plots)
            + '</svg><figcaption>Same spectrum, different directions.</figcaption></figure>')


