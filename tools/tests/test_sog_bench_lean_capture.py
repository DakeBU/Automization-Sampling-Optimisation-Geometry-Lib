"""Capture-binding tests; fixture verdicts here do not run submitted Lean."""
import json
from pathlib import Path
import shutil
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools'))
import sog_bench_lean_capture as capture

CASE = ROOT / 'runs/20261110-bench-local-lean-first/raw'
RECEIPT = '17162dc147147f1e6b7849d4528f3d0f5f5b4dc1266b7d2eb532076428d1fa5c'
bench, runtime = capture.bench, capture.runtime


class CaptureTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        directory = tempfile.TemporaryDirectory()
        cls.addClassCleanup(directory.cleanup)
        packets = Path(directory.name) / 'tasks'
        runtime.export(packets, ['sogb-015'])
        cls.task = packets / 'sogb-015'
        cls.core = runtime.checked_packet(cls.task)

    def test_actual_archive_reconstructs_bytes_but_does_not_score(self):
        record, source = capture.checked_capture(CASE, RECEIPT, self.task)
        self.assertEqual(record['id'], 'sogb-015')
        self.assertEqual(record['native_verification'], 'not-run')
        self.assertIsNone(record['score'])
        self.assertEqual(source, (CASE / 'candidate.lean.txt').read_bytes())
        self.assertIn(b'```lean', source)
        with self.assertRaisesRegex(ValueError, 'receipt digest'):
            capture.checked_capture(CASE, '0' * 64, self.task)

    def test_rehashed_but_repaired_candidate_is_not_the_frozen_output(self):
        with tempfile.TemporaryDirectory() as tmp, patch.object(runtime, 'checked_packet', return_value=self.core):
            copy = Path(tmp) / 'raw'
            shutil.copytree(CASE, copy)
            candidate = (copy / 'candidate.lean.txt').read_bytes().replace(b'```lean\n', b'')
            (copy / 'candidate.lean.txt').write_bytes(candidate)
            frame = capture.bridge.line({'action': 'submit', 'source': candidate.decode('utf-8')})
            (copy / 'first-submit.jsonl').write_bytes(frame)
            receipt = json.loads((copy / 'receipt.json').read_bytes())
            for name, raw in [('candidate.lean.txt', candidate), ('first-submit.jsonl', frame)]:
                receipt['files_sha256'][name] = bench.sha(raw)
            forged = bench.encoded(receipt)
            (copy / 'receipt.json').write_bytes(forged)
            with self.assertRaisesRegex(ValueError, 'original generated bytes'):
                capture.checked_capture(copy, bench.sha(forged), self.task)

    def test_missing_or_mismatched_native_digest_is_not_a_score(self):
        for outcome in ('infrastructure-error', 'proof-rejected', 'changed', 'disk-drift'):
            with self.subTest(outcome=outcome), tempfile.TemporaryDirectory() as tmp:
                out = Path(tmp) / 'out'
                def verifier(**kwargs):
                    submission = kwargs['submission'].read_bytes()
                    self.assertEqual(submission, (CASE / 'candidate.lean.txt').read_bytes())
                    report = {'submission_sha256': 'changed' if outcome == 'changed' else bench.sha(submission),
                              'kind': outcome, 'scope': 'mock-only test; no Lean'}
                    kwargs['output'].mkdir()
                    saved = {**report, 'kind': 'accepted'} if outcome == 'disk-drift' else report
                    (kwargs['output'] / 'result.json').write_bytes(bench.encoded(saved))
                    return report
                with (patch.object(runtime, 'checked_packet', return_value=self.core),
                      patch.object(runtime, 'run_submission', side_effect=verifier),
                      patch.object(capture.bridge, 'require_runtime')):
                    if outcome == 'changed':
                        with self.assertRaisesRegex(ValueError, 'exact frozen source'):
                            capture.verify(CASE, RECEIPT, self.task, out, out, out)
                        self.assertFalse((out / 'outcome.json').exists())
                    elif outcome == 'disk-drift':
                        with self.assertRaisesRegex(ValueError, 'result bytes'):
                            capture.verify(CASE, RECEIPT, self.task, out, out, out)
                        self.assertFalse((out / 'outcome.json').exists())
                    else:
                        result = capture.verify(CASE, RECEIPT, self.task, out, out, out)
                        self.assertEqual(result['score'], None if outcome == 'infrastructure-error' else 0)
                        self.assertFalse(result['live_agentic_feedback'])

    def test_verify_refuses_windows_before_reading_model_data(self):
        with (patch.object(capture.bridge.sys, 'platform', 'win32'),
              patch.object(capture, 'checked_capture') as inspect):
            with self.assertRaisesRegex(RuntimeError, 'no host Lean fallback'):
                capture.verify(CASE, RECEIPT, self.task, CASE, CASE, CASE)
        inspect.assert_not_called()


if __name__ == '__main__':
    unittest.main()
