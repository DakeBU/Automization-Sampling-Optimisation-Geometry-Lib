"""Read back one frozen body-only model candidate and verify it in native isolation."""
from __future__ import annotations

import argparse
from pathlib import Path

import sog_bench_lean_stdio as bridge

runtime, bench = bridge.runtime, bridge.bench
FILES = {'Solution.lean.txt', 'adapter.py', 'candidate.lean.txt', 'first-submit.jsonl',
         'generated-tokens.json', 'generated.txt', 'prompt.json', 'selection.json'}
PLACEHOLDER = b'  -- Replace this comment with your proof.\n'


def read(path: Path, limit: int = bridge.MAX_REQUEST) -> bytes:
    raw, rejection = runtime.read_submission(path, limit)
    if rejection is not None:
        raise ValueError('Invalid captured data file: ' + path.name + ' (' + rejection + ')')
    return raw


def checked_capture(capture: Path, receipt_sha256: str, task: Path) -> tuple[dict, bytes]:
    if (not capture.is_dir() or capture.is_symlink()
            or {p.name for p in capture.iterdir()} != FILES | {'receipt.json'}):
        raise ValueError('Expected only the exact body-only evidence files')
    receipt_raw = read(capture / 'receipt.json')
    if bench.sha(receipt_raw) != receipt_sha256:
        raise ValueError('Frozen capture receipt digest mismatch')
    receipt = bridge.decode(receipt_raw)
    contents = {name: read(capture / name) for name in sorted(FILES)}
    if ({name: bench.sha(raw) for name, raw in contents.items()} != receipt['files_sha256']
            or receipt.get('kind') != 'observed-model-candidate-unverified'
            or receipt.get('native_verification') != 'not-run' or receipt['score'] is not None):
        raise ValueError('Capture data/receipt drift or an already attributed proof verdict')
    item = runtime.checked_packet(task)
    selection = bridge.decode(contents['selection.json'])
    prompt = bridge.decode(contents['prompt.json'])
    if (receipt['id'] != item['id'] or selection['id'] != item['id']
            or selection['kind'] != 'declared-model-candidate-only'
            or selection['split'] != prompt['split'] or prompt['split'] != 'public-dev'
            or selection['family'] != prompt['family'] or selection['binding_sha256'] != item['binding_sha256']
            or type(selection['selected']) is not int or selection['selected'] != 1
            or selection['prompt_sha256'] != bench.sha(contents['prompt.json'])
            or selection['template_sha256'] != bench.sha(contents['Solution.lean.txt'])
            or selection['adapter_sha256'] != bench.sha(contents['adapter.py'])):
        raise ValueError('Capture selection does not match the public-dev fixed target')
    for name in ('prompt.json', 'Solution.lean.txt'):
        if contents[name] != read(task / 'agent' / name):
            raise ValueError('Capture no longer matches the checked agent packet')
    template = contents['Solution.lean.txt']
    prefix = template.removesuffix(PLACEHOLDER)
    messages = selection['messages']
    if (prefix == template or len(messages) != 2
            or messages[1] != {'role': 'user', 'content': prefix.decode('utf-8')}):
        raise ValueError('Body-only capture does not show the exact fixed prefix')
    submission = prefix + contents['generated.txt']
    if (contents['candidate.lean.txt'] != submission
            or contents['first-submit.jsonl'] != bridge.line({'action': 'submit', 'source': submission.decode('utf-8')})):
        raise ValueError('Candidate is not the exact fixed prefix plus original generated bytes')
    tokens = bridge.decode(contents['generated-tokens.json'])
    count = receipt['generated_tokens']
    if (set(tokens) != {'input_ids', 'output_ids'} or type(count) is not int
            or type(selection['max_new_tokens']) is not int or not 0 <= count <= selection['max_new_tokens']
            or any(not isinstance(v, list) or any(type(n) is not int or n < 0 for n in v)
                   for v in tokens.values()) or len(tokens['output_ids']) != count):
        raise ValueError('Invalid recorded token envelope')
    return {'id': item['id'], 'binding_sha256': item['binding_sha256'], 'family': prompt['family'],
            'split': 'public-dev', 'capture_receipt_sha256': receipt_sha256,
            'selection_sha256': bench.sha(contents['selection.json']), 'candidate_sha256': bench.sha(submission),
            'native_verification': 'not-run', 'score': None}, submission


def verify(capture: Path, receipt_sha256: str, task: Path, stage: Path, prepared: Path, output: Path) -> dict:
    bridge.require_runtime()
    capture_info, submitted = checked_capture(capture, receipt_sha256, task)
    output.mkdir(parents=True, exist_ok=False)
    candidate = output / 'submission.txt'
    candidate.write_bytes(submitted)
    candidate.chmod(0o444)
    report = runtime.run_submission(task=task, stage_dir=stage, submission=candidate,
                                    runtime=prepared, output=output / 'verification')
    if report['submission_sha256'] != capture_info['candidate_sha256']:
        raise ValueError('Native verifier report does not bind the exact frozen source')
    result_bytes = read(output / 'verification/result.json')
    if result_bytes != bench.encoded(report):
        raise ValueError('Native verifier result bytes differ from the returned outcome')
    kind = report['kind']
    value = {**capture_info, 'schema_version': 1, 'kind': 'native-one-shot-public-dev-model-candidate',
             'native_verification': kind,
             'score': {'accepted': 1, 'proof-rejected': 0, 'resource-limit': 0}.get(kind),
             'selected': 1, 'verification_sha256': bench.sha(result_bytes),
             'provenance_authenticated': False, 'live_agentic_feedback': False,
             'scope': 'One exact operator-captured answer in a body-only condition. '
                      'No held-out claim, live repair loop or model ranking.'}
    bridge.workspace.write_new(output / 'outcome.json', value)
    return value


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subs = parser.add_subparsers(dest='command', required=True)
    check = subs.add_parser('check')
    native = subs.add_parser('verify')
    for command in (check, native):
        command.add_argument('--capture', required=True, type=Path)
        command.add_argument('--receipt-sha256', required=True)
        command.add_argument('--task', required=True, type=Path)
    for key in ('stage', 'runtime', 'output'):
        native.add_argument('--' + key, required=True, type=Path)
    args = parser.parse_args()
    if args.command == 'check':
        result, _ = checked_capture(args.capture, args.receipt_sha256, args.task)
    else:
        result = verify(args.capture, args.receipt_sha256, args.task, args.stage, args.runtime, args.output)
    print(bench.encoded(result).decode('utf-8'), end='')
    return int(args.command == 'verify' and result['score'] is None)


if __name__ == '__main__':
    raise SystemExit(main())
