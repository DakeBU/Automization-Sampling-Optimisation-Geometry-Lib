def link(url, label):
    return f'<a href="{escape(url, quote=True)}">{escape(label)}</a>'


def read_record():
    return json.loads(RECORD.read_text(encoding="utf-8"))


def check(html, row):
    """Check the final generated page, without treating a quotation as a local proof."""
    record = read_record()
    expected = ['id="paper-evidence"', 'id="paper-lean-progress"', record['revision'],
                "Huanjian Zhou and Taiji Suzuki", "not a main-branch release"]
    for t in row['theorems']:
        item = record['theorems'][t['id']]
        expected.extend([f'id="{t["id"]}-proof"', formula_html(t['formula']),
                         'theorem ' + item['declaration'], escape(item['file'])])
        expected.extend(f'id="{t["id"]}-step-{i:02d}"' for i in range(1, 1 + len(t['steps'])))
    errors = ['Gaussian paper: missing ' + s for s in expected if s not in html]
    if html.count('class="companion-lean gp-code"') != 2 * len(row['theorems']):
        errors.append('Gaussian paper: both statements and proofs need attached closed code folds')
    for bad in ('Main paper results remain open in Lean', 'Lean statement — not formalized yet',
                'data-proof-status="compiled"', '<details open class="companion-lean'):
        if bad in html:
            errors.append('Gaussian paper: misleading status or expanded code: ' + bad)
    return errors


